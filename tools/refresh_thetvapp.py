"""Refresh config/thetvapp_channels.json from live APIs (daily cron step).

Pulls api.ppv.st/api/streams (always-live channels) and thetvapp.st/api/matches.json
(rolling 7-day events), writes the build-time input. Fails soft: on API error keeps
the existing config so today's build still runs.
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request
from datetime import UTC, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "config" / "thetvapp_channels.json"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0 Safari/537.36"
EMBED_PREFIX = "https://taifood-blog.asia/embed/"
PPV_HOSTS = ["ppv.st", "ppv.cx", "ppv.is", "ppv.lc"]


def fetch_json(url: str) -> dict:
    last: Exception | None = None
    hosts = PPV_HOSTS if "api.ppv.st" in url else [None]
    for host in hosts:
        candidate = url.replace("api.ppv.st", f"api.{host}", 1) if host else url
        try:
            req = urllib.request.Request(candidate, headers={"User-Agent": UA, "Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=20) as resp:
                return json.loads(resp.read().decode("utf-8", "replace"))
        except Exception as exc:
            last = exc
    raise last  # type: ignore[misc]


def embed_slug(url: str) -> str | None:
    m = re.search(r"taifood-blog\.asia/embed/(.+)$", url or "")
    return m.group(1) if m else None


def slug_key(slug: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", slug.lower())[:40] or "channel"


def main() -> int:
    now = datetime.now(UTC)
    week = now + timedelta(days=8)
    channels: dict[str, dict] = {}
    events: list[dict] = []

    try:
        streams = fetch_json("https://api.ppv.st/api/streams")
        for cat in streams.get("streams", []):
            for stream in cat.get("streams", []):
                if not stream.get("always_live"):
                    continue
                slug = embed_slug(str(stream.get("iframe", "")).replace("\\/", "/"))
                if not slug:
                    continue
                name = stream.get("name") or slug
                channels[slug] = {
                    "name": f"Grey: {name}",
                    "tvg_id": "grey.tvapp." + re.sub(r"[^a-z0-9]", "-", name.lower())[:30],
                    "embed": EMBED_PREFIX + slug,
                    "always": True,
                }
    except Exception as exc:
        print(f"ppv.st fetch failed: {exc}")

    try:
        matches = fetch_json("https://thetvapp.st/api/matches.json")
        seen: set[str] = set()
        for match in matches:
            starts = match.get("date")
            if not isinstance(starts, (int, float)):
                continue
            start = datetime.fromtimestamp(starts / 1000, tz=UTC)
            if not now - timedelta(hours=2) <= start <= week:
                continue
            for source in match.get("sources", []):
                urls = source.get("urls") or []
                slug = embed_slug(urls[0]) if urls else None
                if not slug or slug in seen:
                    continue
                seen.add(slug)
                title = match.get("title") or slug
                events.append({
                    "name": title,
                    "slug": slug,
                    "start": start.isoformat(),
                    "league": match.get("tagLeague", ""),
                })
                channels.setdefault(slug, {
                    "name": f"Grey: {title}",
                    "tvg_id": "grey.tvapp.ev." + slug_key(slug),
                    "embed": EMBED_PREFIX + slug,
                    "always": False,
                })
                break
    except Exception as exc:
        print(f"thetvapp matches fetch failed: {exc}")

    if not channels:
        if CONFIG.exists():
            print("no live data fetched; keeping existing config")
            return 0
        print("no live data and no existing config; writing empty")
        CONFIG.write_text(json.dumps({"_comment": "empty fallback", "channels": {}, "events": []}, indent=2) + "\n", encoding="utf-8")
        return 0

    payload = {
        "_comment": (
            "thetvapp/ppv.st grey overlay: always-live network channels + rolling 7-day "
            "game events. Regenerated by tools/refresh_thetvapp.py from the live APIs; "
            "resolved at build time by tools/build_thetvapp.py (headless browser)."
        ),
        "generated_at": now.isoformat(),
        "channels": dict(sorted(channels.items())),
        "events": sorted(events, key=lambda e: e["start"]),
    }
    CONFIG.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"thetvapp config refreshed: {len(channels)} channels, {len(events)} events")
    return 0


if __name__ == "__main__":
    sys.exit(main())
